    required this.sections,
  });
}

final recommendationServiceProvider = Provider<RecommendationService>((ref) {
  return RecommendationService();
});

final homeFeedProvider = StateNotifierProvider<HomeFeedNotifier, AsyncValue<HomeFeedData>>((ref) {
  final service = ref.watch(recommendationServiceProvider);
  return HomeFeedNotifier(service, ref);
});

class HomeFeedNotifier extends StateNotifier<AsyncValue<HomeFeedData>> {
  final RecommendationService _service;
  final Ref _ref;
  DateTime? _lastGeneratedTime;
  Timer? _dailyCycleTimer;

  HomeFeedNotifier(this._service, this._ref) : super(const AsyncValue.loading()) {
    refreshFeed();

    // 1. Reactive trigger: Automatically re-generate algorithm when user plays any song
    _ref.listen(playerStateProvider.select((s) => s.currentSong?.id), (previous, next) {
      if (next != null && next != previous) {
        refreshFeed();
      }
    });



    // 3. Network reconnection trigger: When internet comes back ON, immediately refresh daily trend data
    _ref.listen(networkStatusProvider, (previous, next) {
      if (next == NetworkStatus.online && previous != NetworkStatus.online) {
        refreshFeed();
      }
    });

    // 4. Daily 5:30 AM IST timer check (runs every minute to catch 5:30 AM IST boundary while app is open)
    _dailyCycleTimer = Timer.periodic(const Duration(minutes: 1), (_) {
      final mostRecent530Am = _getMostRecent530AmIst();
      if (_lastGeneratedTime != null && _lastGeneratedTime!.isBefore(mostRecent530Am)) {
        refreshFeed();
      }
    });
  }

  /// Calculates the most recent 5:30 AM IST timestamp (UTC 00:00)
  static DateTime _getMostRecent530AmIst() {
    final nowUtc = DateTime.now().toUtc();
    final today530AmIst = DateTime.utc(nowUtc.year, nowUtc.month, nowUtc.day, 0, 0, 0);
    if (nowUtc.isBefore(today530AmIst)) {
      return today530AmIst.subtract(const Duration(days: 1));
    }
    return today530AmIst;
  }

  Future<void> refreshFeed() async {
    try {
      final currentSong = _ref.read(playerStateProvider).currentSong;
      final feed = await _service.generateHomeFeed(currentSong: currentSong);
      _lastGeneratedTime = DateTime.now().toUtc();
      state = AsyncValue.data(feed);
    } catch (e) {
      final currentSong = _ref.read(playerStateProvider).currentSong;
      final fallback = _service.generateLocalAlgorithmicFeed(currentSong: currentSong);
      _lastGeneratedTime = DateTime.now().toUtc();
      state = AsyncValue.data(fallback);
    }
  }

  @override
  void dispose() {
    _dailyCycleTimer?.cancel();
    super.dispose();
  }
}

class RecommendationService {
  final Dio _dio = Dio(BaseOptions(
    connectTimeout: const Duration(milliseconds: 1200),
    receiveTimeout: const Duration(milliseconds: 1200),
  ));

  /// Generates the dynamic algorithmic Home Feed with Gemini AI trend analysis
  Future<HomeFeedData> generateHomeFeed({Song? currentSong}) async {
    // 1. Fetch latest songs from PostgreSQL DB (paginated 100 tracks)
    try {
      final candidateEndpoints = [
        '${AppConstants.defaultApiBaseUrl}/songs?limit=100',
        ...AppConstants.fallbackApiBaseUrls.map((u) => '$u/songs?limit=100'),
      ];

      for (final endpoint in candidateEndpoints) {
        try {
          final songsRes = await _dio.get(endpoint);
          if (songsRes.statusCode == 200 && songsRes.data != null) {
            final data = songsRes.data;
            final list = (data is Map ? (data['data'] ?? data['songs']) : data) as List<dynamic>?;
            if (list != null && list.isNotEmpty) {
              for (final item in list) {
                final songId = (item['id'] ?? '').toString();
                if (songId.isNotEmpty) {
                  final newSong = Song(
                    id: songId,
                    title: (item['title'] ?? 'Untitled Track').toString(),
                    artist: (item['artistName'] ?? item['artist']?['name'] ?? item['artist'] ?? 'Unknown Artist').toString(),
                    album: (item['albumName'] ?? item['album']?['title'] ?? item['album'] ?? 'Single').toString(),
                    movieName: item['movieName']?.toString(),
                    artworkUrl: (item['artworkUrl'] ?? item['artwork'] ?? '').toString(),
                    audioUrl: (item['audioUrl'] ?? '').toString(),
                    duration: (item['duration'] as num?)?.toInt() ?? 180,
                    genre: (item['genre'] ?? 'Music').toString(),
                    language: (item['language'] ?? 'Tamil').toString(),
                    lyrics: (item['lyrics'] is List) ? List<String>.from(item['lyrics']) : [],
                  );
                  MockMusicCatalog.syncSong(newSong);
                }
              }
              break;
            }
          }
        } catch (_) {}
      }
    } catch (_) {}

    final localFeed = generateLocalAlgorithmicFeed(currentSong: currentSong);

    try {
      final res = await _dio.get(
        '${AppConstants.defaultApiBaseUrl}/recommendations/trending',
      );

      if (res.statusCode == 200 && res.data != null) {
        final data = res.data as Map<String, dynamic>;
        final spotlight = data['dailySpotlight'] as Map<String, dynamic>?;
        if (spotlight != null && localFeed.aiSpotlight != null) {
          final updatedSpotlight = AiSpotlightData(
            title: spotlight['title'] ?? localFeed.aiSpotlight!.title,
            rationale: spotlight['rationale'] ?? localFeed.aiSpotlight!.rationale,
            badge: spotlight['badge'] ?? localFeed.aiSpotlight!.badge,
            featuredSong: localFeed.aiSpotlight!.featuredSong,
            playlist: localFeed.aiSpotlight!.playlist,
          );
          return HomeFeedData(
            greeting: localFeed.greeting,
            quickPlaySongs: localFeed.quickPlaySongs,
            aiSpotlight: updatedSpotlight,
            sections: localFeed.sections,
          );
        }
      }
    } catch (_) {
      // Offline fallback
    }

    return localFeed;
  }

  /// 100% Dynamic Spotify & Gemini AI Recommendation Engine
