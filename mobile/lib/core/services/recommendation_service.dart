  /// Generates the dynamic algorithmic Home Feed with Gemini AI trend analysis
  Future<HomeFeedData> generateHomeFeed({Song? currentSong}) async {
    // 1. Fetch latest songs from PostgreSQL DB (live sync)
    try {
      final timestamp = DateTime.now().millisecondsSinceEpoch;
      final candidateEndpoints = [
        '${AppConstants.defaultApiBaseUrl}/songs?limit=10000&nocache=1&t=$timestamp',
        ...AppConstants.fallbackApiBaseUrls.map((u) => '$u/songs?limit=10000&nocache=1&t=$timestamp'),
      ];

      for (final endpoint in candidateEndpoints) {
        try {
          final songsRes = await _dio.get(endpoint);
          if (songsRes.statusCode == 200 && songsRes.data != null) {
            final data = songsRes.data;
            final list = (data is Map ? (data['data'] ?? data['songs']) : data) as List<dynamic>?;
            if (list != null && list.isNotEmpty) {
              for (final item in list) {
                final songId = (item['id'] ?? '').toString();
                if (songId.isNotEmpty) {
                  final newSong = Song(
                    id: songId,
                    title: (item['title'] ?? 'Untitled Track').toString(),
                    artist: (item['artistName'] ?? item['artist']?['name'] ?? item['artist'] ?? 'Unknown Artist').toString(),
                    album: (item['albumName'] ?? item['album']?['title'] ?? item['album'] ?? 'Single').toString(),
                    movieName: item['movieName']?.toString(),
                    artworkUrl: (item['artworkUrl'] ?? item['artwork'] ?? '').toString(),
                    audioUrl: (item['audioUrl'] ?? '').toString(),
                    duration: (item['duration'] as num?)?.toInt() ?? 180,
                    genre: (item['genre'] ?? 'Music').toString(),
                    language: (item['language'] ?? 'Tamil').toString(),
                    lyrics: (item['lyrics'] is List) ? List<String>.from(item['lyrics']) : [],
                  );
                  MockMusicCatalog.syncSong(newSong);
                }
              }
              break;
            }
          }
        } catch (_) {}
      }
    } catch (_) {}

    final localFeed = generateLocalAlgorithmicFeed(currentSong: currentSong);

    try {
      final res = await _dio.get(
        '${AppConstants.defaultApiBaseUrl}/recommendations/trending',
      );

      if (res.statusCode == 200 && res.data != null) {
        final data = res.data as Map<String, dynamic>;
        final spotlight = data['dailySpotlight'] as Map<String, dynamic>?;
        if (spotlight != null && localFeed.aiSpotlight != null) {
          final updatedSpotlight = AiSpotlightData(
            title: spotlight['title'] ?? localFeed.aiSpotlight!.title,
            rationale: spotlight['rationale'] ?? localFeed.aiSpotlight!.rationale,
            badge: spotlight['badge'] ?? localFeed.aiSpotlight!.badge,
            featuredSong: localFeed.aiSpotlight!.featuredSong,
            playlist: localFeed.aiSpotlight!.playlist,
          );
          return HomeFeedData(
            greeting: localFeed.greeting,
            quickPlaySongs: localFeed.quickPlaySongs,
            quickPlayCards: localFeed.quickPlayCards,
            aiSpotlight: updatedSpotlight,
            sections: localFeed.sections,
          );
        }
      }
    } catch (_) {
      // Offline fallback
    }

    return localFeed;
  }

