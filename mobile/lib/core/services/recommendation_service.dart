      for (final s in allSongs) {
        if (quickPlay.length < 6 && !quickPlayIds.contains(s.id)) {
          quickPlay.add(s);
          quickPlayIds.add(s.id);
        }
      }
    }

    // 3. Gemini AI Live Tamil Trending Songs & Playlists Analysis
    final trendingSongs = List<Song>.from(allSongs);
    trendingSongs.sort((a, b) {
      final aTrendWeight = _getSongTrendWeight(a);
      final bTrendWeight = _getSongTrendWeight(b);
      return bTrendWeight.compareTo(aTrendWeight);
    });

    final massAnthems = allSongs.where((s) {
      final t = s.title.toLowerCase();
      final m = (s.movieName ?? s.album).toLowerCase();
      final g = s.genre.toLowerCase();
      return g.contains('dance') ||
          g.contains('hip-hop') ||
          t.contains('matta') ||
